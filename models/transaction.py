from datetime import datetime, timezone  # Импорт классов для работы с датами и часовыми поясами
import uuid  # Импорт модуля для генерации глобально уникальных идентификаторов
from db.manager import get_conn  # Импорт функции безопасного получения соединения с основной БД

def create_transaction(operator_id: int, action_type: str, details: str | None = None) -> dict:  # Функция регистрации новой транзакции; возвращает словарь с данными записи
    ts = datetime.now(timezone.utc).isoformat()  # Генерация метки времени в стандарте ISO 8601 с привязкой к UTC
    ref_id = f"{uuid.uuid4().hex[:8]}-{action_type}"  # Формирование короткого уникального референса на основе обрезанного UUID и типа действия

    with get_conn() as conn:  # Открытие соединения в транзакционном контексте (авто-фиксация или откат при завершении блока)
        c = conn.cursor()  # Создание курсора для изолированного выполнения запросов
        c.execute(  # Выполнение подготовленного запроса вставки данных
            """
            INSERT INTO transactions (ts, operator_id, action_type, details, ref_id)
            VALUES (?, ?, ?, ?, ?)
            """,
            (ts, operator_id, action_type, details, ref_id)  # Передача значений в строгом порядке столбцов таблицы
        )
        conn.commit()  # Явная фиксация изменений (избыточна, так как контекстный менеджер sqlite3 делает это автоматически)
        new_id = c.lastrowid  # Получение автоматически присвоенного первичного ключа новой строки

    return {  # Формирование и возврат словаря-ответа клиентской части или логике маршрутов
        "id": new_id,  # Внутренний идентификатор записи в таблице БД
        "ts": ts,  # Временная метка события
        "ref_id": ref_id,  # Уникальный внешний идентификатор для трекинга
        "operator_id": operator_id,  # Ссылка на оператора, инициировавшего действие
        "action_type": action_type,  # Категория или тип выполненной операции
        "details": details  # Произвольное описание или дополнительные параметры
    }